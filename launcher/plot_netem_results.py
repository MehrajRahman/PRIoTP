def fig_cross_condition_loss(all_kpi, conditions_labels, save_path):
    """Grouped bar chart: mean loss (%) per sensor across conditions."""
    sensors = sorted({row["sensor"] for rows in all_kpi.values() for row in rows})
    fig, ax = plt.subplots(figsize=(DBL_W, DBL_W / GOLDEN / 1.5))
    n_cond = len(conditions_labels)
    n_sens = len(sensors)
    w = 0.8 / n_cond
    cmap = plt.cm.Set2

    for ci, cond in enumerate(conditions_labels):
        rows = all_kpi.get(cond, [])
        sensor_loss = defaultdict(list)
        for r in rows:
            sensor_loss[r["sensor"]].append(r["loss_pct"])
        means = [np.mean(sensor_loss.get(s, [0])) for s in sensors]
        stds = [np.std(sensor_loss.get(s, [0])) for s in sensors]
        x = np.arange(n_sens) + ci * w
        ax.bar(x, means, w, yerr=stds, capsize=2, label=cond.replace("_", " "),
               color=cmap(ci), edgecolor="white", linewidth=0.5)

    ax.set_xticks(np.arange(n_sens) + w * (n_cond - 1) / 2)
    ax.set_xticklabels(sensors, rotation=30, ha="right")
    ax.set_ylabel("Packet Loss (%)")
    ax.set_title("Packet Loss Across Network Conditions")
    ax.legend(title="Condition", bbox_to_anchor=(1.02, 1), loc="upper left",
              fontsize=7)
    fig.tight_layout()
    fig.savefig(save_path)
    plt.close(fig)


def fig_cross_condition_delay(all_delays, conditions_labels, save_path):
    """Box plot: delay distribution across conditions (all sensors combined)."""
    fig, ax = plt.subplots(figsize=(DBL_W, DBL_W / GOLDEN / 1.5))

    data = []
    labels = []
    for cond in conditions_labels:
        delays = all_delays.get(cond, {})
        combined = np.concatenate(list(delays.values())) if delays else np.array([0])
        data.append(combined)
        labels.append(cond.replace("_", " "))

    bp = ax.boxplot(data, tick_labels=labels, patch_artist=True, showfliers=False,
                    medianprops=dict(color="black", linewidth=1.5),
                    whiskerprops=dict(linewidth=0.8),
                    boxprops=dict(linewidth=0.8))

    cmap = plt.cm.Set2
    for i, patch in enumerate(bp["boxes"]):
        patch.set_facecolor(cmap(i))
        patch.set_alpha(0.8)

    ax.set_ylabel("End-to-End Delay (ms)")
    ax.set_title("Delivery Delay Distribution Across Conditions")
    plt.xticks(rotation=30, ha="right")
    fig.tight_layout()
    fig.savefig(save_path)
    plt.close(fig)


def fig_cross_condition_action_shift(all_decisions, conditions_labels, save_path):
    """Stacked bar chart: how action proportion changes across conditions.
    This is the key figure showing Q-agent adaptation."""
    fig, ax = plt.subplots(figsize=(DBL_W, DBL_W / GOLDEN / 1.5))

    action_order = ["RELIABLE", "UNRELIABLE", "DROP"]
    bars_data = {a: [] for a in action_order}

    for cond in conditions_labels:
        decs = all_decisions.get(cond, [])
        total = len(decs) if decs else 1
        for a in action_order:
            count = sum(1 for d in decs if d["action"] == a)
            bars_data[a].append(100.0 * count / total)

    x = np.arange(len(conditions_labels))
    bottom = np.zeros(len(conditions_labels))

    for action in action_order:
        vals = np.array(bars_data[action])
        ax.bar(x, vals, 0.6, bottom=bottom, label=action,
               color=COLORS[action], edgecolor="white", linewidth=0.5)
        # Annotate percentages in the middle of each segment
        for i, (v, b) in enumerate(zip(vals, bottom)):
            if v > 5:
                ax.text(i, b + v / 2, f"{v:.0f}%", ha="center", va="center",
                        fontsize=7, color="white", fontweight="bold")
        bottom += vals

    ax.set_xticks(x)
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=7)
    ax.set_ylabel("Action Proportion (%)")
    ax.set_ylim(0, 105)
    ax.set_title("Q-Agent Policy Shift Under Network Impairment")
    ax.legend(loc="upper right", framealpha=0.9)
    fig.tight_layout()
    fig.savefig(save_path)
    plt.close(fig)


def fig_cross_condition_rtt_distribution(all_decisions, conditions_labels, save_path):
    """Grouped bar chart showing RTT level distribution (LOW vs HIGH) across conditions."""
    fig, ax = plt.subplots(figsize=(DBL_W, DBL_W / GOLDEN / 1.8))

    low_pcts = []
    high_pcts = []
    for cond in conditions_labels:
        decs = all_decisions.get(cond, [])
        total = len(decs) if decs else 1
        n_low = sum(1 for d in decs if d["rtt_level"] == 0)
        n_high = sum(1 for d in decs if d["rtt_level"] == 1)
        low_pcts.append(100.0 * n_low / total)
        high_pcts.append(100.0 * n_high / total)

    x = np.arange(len(conditions_labels))
    w = 0.35

    ax.bar(x - w / 2, low_pcts, w, label="LOW RTT (≤150ms)",
           color=COLORS["baseline"], edgecolor="white")
    ax.bar(x + w / 2, high_pcts, w, label="HIGH RTT (>150ms)",
           color=COLORS["DROP"], edgecolor="white")

    for i, (lo, hi) in enumerate(zip(low_pcts, high_pcts)):
        if lo > 3:
            ax.text(i - w / 2, lo + 1, f"{lo:.0f}%", ha="center", fontsize=7)
        if hi > 3:
            ax.text(i + w / 2, hi + 1, f"{hi:.0f}%", ha="center", fontsize=7)

    ax.set_xticks(x)
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=7)
    ax.set_ylabel("Proportion (%)")
    ax.set_ylim(0, 115)
    ax.set_title("RTT State Distribution Across Conditions")
    ax.legend(framealpha=0.9)
    fig.tight_layout()
    fig.savefig(save_path)
    plt.close(fig)


def fig_cross_condition_delay_cdf(all_delays, conditions_labels, save_path):
    """Overlay CDF of delivery delay for each condition (all sensors combined).
    This is a standard networking figure showing the impact of impairment."""
    fig, ax = plt.subplots(figsize=(COL_W * 1.3, COL_W / GOLDEN))
    cmap = plt.cm.tab10

    for ci, cond in enumerate(conditions_labels):
        delays = all_delays.get(cond, {})
        if not delays:
            continue
        combined = np.sort(np.concatenate(list(delays.values())))
        cdf = np.arange(1, len(combined) + 1) / len(combined)
        ax.plot(combined, cdf, color=cmap(ci), label=cond.replace("_", " "),
                linewidth=1.3)

    ax.set_xlabel("End-to-End Delay (ms)")
    ax.set_ylabel("CDF")
    ax.set_title("Delivery Delay CDF Across Conditions")
    ax.set_ylim(0, 1.05)
    ax.legend(loc="lower right", fontsize=7, framealpha=0.9)
    fig.tight_layout()
    fig.savefig(save_path)
    plt.close(fig)


def fig_cross_condition_kernel_rtt(kernel_ping_avg, conditions_labels, save_path):
    """Bar chart of kernel-level RTT sanity check from netem_ping.txt.
    This validates that tc/netem actually injected delay regardless of
    protocol-internal RTT estimator behavior.
    """
    vals = []
    for cond in conditions_labels:
        v = kernel_ping_avg.get(cond)
        vals.append(v if v is not None else 0.0)

    fig, ax = plt.subplots(figsize=(DBL_W, DBL_W / GOLDEN / 1.8))
    x = np.arange(len(conditions_labels))
    cmap = plt.cm.Set2
    bars = ax.bar(x, vals,
                  color=[cmap(i) for i in range(len(conditions_labels))],
                  edgecolor="white", linewidth=0.5)

    for i, (bar, v) in enumerate(zip(bars, vals)):
        if v > 0:
            ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 3,
                    f"{v:.1f}", ha="center", va="bottom", fontsize=7)

    ax.set_xticks(x)
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=7)
    ax.set_ylabel("Kernel RTT Avg (ms)")
    ax.set_title("NetEm Sanity Check: Kernel-Level RTT by Condition")
    fig.tight_layout()
    fig.savefig(save_path)
    plt.close(fig)


def fig_summary_dashboard(all_kpi, all_decisions, all_delays,
                          conditions_labels, save_path):
    """A 2×2 summary dashboard combining key metrics for a quick visual overview."""
    fig, axes = plt.subplots(2, 2, figsize=(DBL_W, DBL_W / 1.2))
    fig.suptitle("PRIoTP Performance Under Network Impairment", fontsize=11,
                 fontweight="bold", y=0.98)

    # (0,0) — Mean loss per condition
    ax = axes[0, 0]
    means = []
    stds = []
    for cond in conditions_labels:
        rows = all_kpi.get(cond, [])
        losses = [r["loss_pct"] for r in rows] if rows else [0]
        means.append(np.mean(losses))
        stds.append(np.std(losses))
    cmap = plt.cm.Set2
    bars = ax.bar(range(len(conditions_labels)), means, yerr=stds, capsize=3,
                  color=[cmap(i) for i in range(len(conditions_labels))],
                  edgecolor="white", linewidth=0.5)
    ax.set_xticks(range(len(conditions_labels)))
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=6)
    ax.set_ylabel("Loss (%)")
    ax.set_title("Mean Packet Loss", fontsize=9)

    # (0,1) — Action mix stacked bar
    ax = axes[0, 1]
    action_order = ["RELIABLE", "UNRELIABLE", "DROP"]
    bottom = np.zeros(len(conditions_labels))
    x = np.arange(len(conditions_labels))
    for action in action_order:
        vals = []
        for cond in conditions_labels:
            decs = all_decisions.get(cond, [])
            total = len(decs) if decs else 1
            vals.append(100.0 * sum(1 for d in decs if d["action"] == action) / total)
        vals = np.array(vals)
        ax.bar(x, vals, 0.6, bottom=bottom, label=action,
               color=COLORS[action], edgecolor="white", linewidth=0.3)
        bottom += vals
    ax.set_xticks(x)
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=6)
    ax.set_ylabel("Proportion (%)")
    ax.set_title("Q-Agent Action Mix", fontsize=9)
    ax.legend(fontsize=6, loc="upper right")
    ax.set_ylim(0, 105)

    # (1,0) — Delay box plot
    ax = axes[1, 0]
    data = []
    for cond in conditions_labels:
        delays = all_delays.get(cond, {})
        combined = np.concatenate(list(delays.values())) if delays else np.array([0])
        data.append(combined)
    bp = ax.boxplot(data, patch_artist=True, showfliers=False,
                    medianprops=dict(color="black", linewidth=1),
                    whiskerprops=dict(linewidth=0.6),
                    boxprops=dict(linewidth=0.6))
    for i, patch in enumerate(bp["boxes"]):
        patch.set_facecolor(cmap(i))
        patch.set_alpha(0.8)
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=6)
    ax.set_ylabel("Delay (ms)")
    ax.set_title("Delivery Delay", fontsize=9)

    # (1,1) — RTT state proportion
    ax = axes[1, 1]
    low_pcts = []
    high_pcts = []
    for cond in conditions_labels:
        decs = all_decisions.get(cond, [])
        total = len(decs) if decs else 1
        low_pcts.append(100.0 * sum(1 for d in decs if d["rtt_level"] == 0) / total)
        high_pcts.append(100.0 * sum(1 for d in decs if d["rtt_level"] == 1) / total)
    w = 0.35
    ax.bar(x - w / 2, low_pcts, w, label="LOW RTT", color=COLORS["baseline"])
    ax.bar(x + w / 2, high_pcts, w, label="HIGH RTT", color=COLORS["DROP"])
    ax.set_xticks(x)
    ax.set_xticklabels([c.replace("_", "\n") for c in conditions_labels], fontsize=6)
    ax.set_ylabel("Proportion (%)")
    ax.set_title("RTT State Distribution", fontsize=9)
    ax.legend(fontsize=6)
    ax.set_ylim(0, 115)

    fig.tight_layout(rect=[0, 0, 1, 0.95])
    fig.savefig(save_path)
    plt.close(fig)


