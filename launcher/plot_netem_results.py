def process_single_run(results_dir, fig_dir, fmt, label=""):
    """Generate figures for a single benchmark run."""
    suffix = f" ({label})" if label else ""

    server_log = os.path.join(results_dir, "prtp_server.log")
    kpi_csv = os.path.join(results_dir, "delivery_kpi.csv")

    decisions = []
    kpi_rows = []
    delays = {}

    if os.path.isfile(server_log):
        decisions = parse_q_decisions(server_log)

    if os.path.isfile(kpi_csv):
        kpi_rows = parse_delivery_kpi(kpi_csv)

    delays = parse_delivery_delays(results_dir)

    prefix = f"{label}_" if label else ""
    generated = []

    if decisions:
        p = os.path.join(fig_dir, f"{prefix}q_convergence.{fmt}")
        fig_q_value_convergence(decisions, p)
        generated.append(p)

        p = os.path.join(fig_dir, f"{prefix}action_distribution.{fmt}")
        fig_action_distribution_bar(decisions, p, suffix)
        generated.append(p)

        p = os.path.join(fig_dir, f"{prefix}action_timeline.{fmt}")
        fig_action_timeline(decisions, p, suffix)
        generated.append(p)

        p = os.path.join(fig_dir, f"{prefix}rtt_vs_action.{fmt}")
        fig_rtt_vs_action(decisions, p)
        generated.append(p)

    if delays:
        p = os.path.join(fig_dir, f"{prefix}delay_cdf.{fmt}")
        fig_delivery_delay_cdf(delays, p, suffix)
        generated.append(p)

    if kpi_rows:
        p = os.path.join(fig_dir, f"{prefix}sensor_loss.{fmt}")
        fig_per_sensor_loss(kpi_rows, p, suffix)
        generated.append(p)

    return decisions, kpi_rows, delays, generated


def main():
    parser = argparse.ArgumentParser(
        description="Generate publication-quality figures from PRIoTP benchmark results.")
    parser.add_argument("results_dir",
                        help="Path to benchmark_results_* or netem_experiment_* directory")
    parser.add_argument("--output", "-o", default=None,
                        help="Output directory for figures (default: <results_dir>/figures/)")
    parser.add_argument("--format", "-f", default="png", choices=["png", "pdf", "svg"],
                        help="Output figure format (default: png)")
    args = parser.parse_args()

    results_dir = os.path.abspath(args.results_dir)
    fmt = args.format

    if not os.path.isdir(results_dir):
        print(f"ERROR: Directory not found: {results_dir}")
        sys.exit(1)

    fig_dir = args.output or os.path.join(results_dir, "figures")
    os.makedirs(fig_dir, exist_ok=True)

    # Determine mode: multi-condition or single-run
    conditions = detect_conditions(results_dir)

    # Also try to find and plot Q-table heatmap
    qtable_path = None
    for candidate in [os.path.join(results_dir, "q_agent_trained.csv"),
                      os.path.join(os.path.dirname(results_dir), "q_agent_trained.csv"),
                      os.path.join(os.path.dirname(results_dir), "launcher", "q_agent_trained.csv")]:
        if os.path.isfile(candidate):
            qtable_path = candidate
            break

    all_figures = []

    if qtable_path:
        qtable = parse_q_table(qtable_path)
        p = os.path.join(fig_dir, f"q_policy_heatmap.{fmt}")
        fig_q_policy_heatmap(qtable, p)
        all_figures.append(p)
        print(f"  [fig] Q-Policy Heatmap → {os.path.basename(p)}")

    if conditions:
        # ── Multi-condition mode ─────────────────────────────────────────────
        print(f"\nMulti-condition experiment detected ({len(conditions)} conditions)")
        print(f"Output: {fig_dir}/\n")

        all_decisions = OrderedDict()
        all_kpi = OrderedDict()
        all_delays = OrderedDict()
        all_kernel_ping_avg = OrderedDict()
        cond_labels = list(conditions.keys())

        for label, cond_dir in conditions.items():
            print(f"  Processing: {label}")
            decs, kpi, delays, figs = process_single_run(cond_dir, fig_dir, fmt, label)
            all_decisions[label] = decs
            all_kpi[label] = kpi
            all_delays[label] = delays
            all_kernel_ping_avg[label] = parse_ping_rtt_avg(os.path.join(cond_dir, "netem_ping.txt"))
            all_figures.extend(figs)

        # Cross-condition comparison figures
        print(f"\n  Generating cross-condition figures...")

        p = os.path.join(fig_dir, f"cross_loss.{fmt}")
        fig_cross_condition_loss(all_kpi, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] Cross-Condition Loss → {os.path.basename(p)}")

        p = os.path.join(fig_dir, f"cross_delay_boxplot.{fmt}")
        fig_cross_condition_delay(all_delays, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] Cross-Condition Delay → {os.path.basename(p)}")

        p = os.path.join(fig_dir, f"cross_action_shift.{fmt}")
        fig_cross_condition_action_shift(all_decisions, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] Action Policy Shift → {os.path.basename(p)}")

        p = os.path.join(fig_dir, f"cross_rtt_distribution.{fmt}")
        fig_cross_condition_rtt_distribution(all_decisions, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] RTT State Distribution → {os.path.basename(p)}")

        p = os.path.join(fig_dir, f"cross_delay_cdf.{fmt}")
        fig_cross_condition_delay_cdf(all_delays, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] Overlay Delay CDF → {os.path.basename(p)}")

        p = os.path.join(fig_dir, f"cross_kernel_rtt.{fmt}")
        fig_cross_condition_kernel_rtt(all_kernel_ping_avg, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] Kernel RTT Sanity → {os.path.basename(p)}")

        p = os.path.join(fig_dir, f"summary_dashboard.{fmt}")
        fig_summary_dashboard(all_kpi, all_decisions, all_delays, cond_labels, p)
        all_figures.append(p)
        print(f"    [fig] Summary Dashboard → {os.path.basename(p)}")

    else:
        # ── Single-run mode ──────────────────────────────────────────────────
        print(f"\nSingle-run mode")
        print(f"Input:  {results_dir}")
        print(f"Output: {fig_dir}/\n")

        _, _, _, figs = process_single_run(results_dir, fig_dir, fmt)
        all_figures.extend(figs)

    # Summary
    print(f"\n{'=' * 60}")
    print(f"  Generated {len(all_figures)} figures in {fig_dir}/")
    print(f"{'=' * 60}")
    for f in all_figures:
        print(f"    {os.path.basename(f)}")
    print()


if __name__ == "__main__":
    main()
