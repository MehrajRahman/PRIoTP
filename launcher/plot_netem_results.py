def parse_q_decisions(server_log_path):
    """Parse Q-Decision lines from prtp_server.log.
    Returns list of dicts with keys: sensor, rtt_ms, rtt_level, importance,
    action, q_value, line_number (used as a proxy for time ordering).
    """
    pattern = re.compile(
        r"Q-Decision:\s+(\S+)\s+\|\s+RTT=(\d+)ms\(lvl=(\d)\)\s+\|\s+IMP=(\w+)\s+\|\s+ACTION=(\w+)\s+\|\s+Q=([\-\d.]+)"
    )
    decisions = []
    with open(server_log_path) as f:
        for i, line in enumerate(f):
            m = pattern.search(line)
            if m:
                decisions.append({
                    "idx":        i,
                    "sensor":     m.group(1),
                    "rtt_ms":     int(m.group(2)),
                    "rtt_level":  int(m.group(3)),
                    "importance": m.group(4),
                    "action":     m.group(5),
                    "q_value":    float(m.group(6)),
                })
    return decisions


def parse_delivery_kpi(csv_path):
    """Parse delivery_kpi.csv (generated by analyze_localhost_results.py)."""
    rows = []
    with open(csv_path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            for k in ("sensor_sent", "server_got", "client_got", "lost"):
                row[k] = int(row[k])
            for k in ("loss_pct", "mean_delay_ms", "p95_delay_ms", "p99_delay_ms"):
                row[k] = float(row[k])
            rows.append(row)
    return rows


def parse_delivery_delays(results_dir):
    """Compute per-packet delays from client_*_sensor_log/ and sensor_log/.

    Returns dict[sensor] -> numpy array of per-packet delays in ms.
    """
    sensor_dir = os.path.join(results_dir, "sensor_log")
    delays_by_sensor = {}

    if not os.path.isdir(sensor_dir):
        return delays_by_sensor

    # Read all sensor sent logs
    sent = {}  # sensor -> {seq: timestamp}
    for lf in glob.glob(os.path.join(sensor_dir, "*.log")):
        sensor = os.path.splitext(os.path.basename(lf))[0]
        sent[sensor] = {}
        with open(lf) as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) >= 2:
                    try:
                        ts = float(parts[0])
                        seq = int(parts[1])
                        sent[sensor][seq] = ts
                    except (ValueError, IndexError):
                        continue

    # Read client receive logs and compute delays (use client 1 as representative)
    client_dir = os.path.join(results_dir, "client1_sensor_log")
    if not os.path.isdir(client_dir):
        return delays_by_sensor

    for lf in glob.glob(os.path.join(client_dir, "*.log")):
        sensor = os.path.splitext(os.path.basename(lf))[0]
        if sensor not in sent:
            continue
        d = []
        with open(lf) as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) >= 2:
                    try:
                        recv_ts = float(parts[0])
                        seq = int(parts[1])
                        if seq in sent[sensor]:
                            delay_ms = (recv_ts - sent[sensor][seq]) * 1000.0
                            if delay_ms >= 0:
                                d.append(delay_ms)
                    except (ValueError, IndexError):
                        continue
        if d:
            delays_by_sensor[sensor] = np.array(d)

    return delays_by_sensor


def parse_q_table(csv_path):
    """Parse q_agent_trained.csv → 2×3×3 array."""
    qtable = np.zeros((2, 3, 3))
    with open(csv_path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            r = int(row["rtt"])
            i = int(row["importance"])
            a = int(row["action"])
            qtable[r, i, a] = float(row["q_value"])
    return qtable


def parse_pidstat_cpu(pidstat_path):
    """Parse pidstat_server.csv → list of (time_offset_s, cpu_pct)."""
    samples = []
    first_ts = None
    with open(pidstat_path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or line.startswith("Linux"):
                continue
            parts = line.split()
            if len(parts) < 8:
                continue
            # Detect CPU section: has %usr header or numeric CPU% value
            try:
                # Handle AM/PM format: parts[0]=HH:MM:SS parts[1]=AM/PM
                offset = 1 if parts[1] in ("AM", "PM") else 0
                usr_pct = float(parts[3 + offset])
                sys_pct = float(parts[4 + offset])
                cpu_pct = float(parts[7 + offset])
                # Only take CPU lines (they have %CPU)
                if "PRTP_server" in line or "PRTP_client" in line:
                    if cpu_pct >= 0:
                        if first_ts is None:
                            first_ts = len(samples)
                        samples.append(cpu_pct)
            except (ValueError, IndexError):
                continue
    return samples


def detect_conditions(experiment_dir):
    """Detect condition_*/ subdirectories within a netem experiment dir.
    Returns: OrderedDict[label -> path]
    """
    conditions = OrderedDict()
    # Read manifest if available
    manifest = os.path.join(experiment_dir, "experiment_manifest.json")
    if os.path.isfile(manifest):
        with open(manifest) as f:
            data = json.load(f)
        for c in data.get("conditions", []):
            cdir = os.path.join(experiment_dir,
                                f"condition_{c['index']}_{c['label']}")
            if os.path.isdir(cdir):
                conditions[c["label"]] = cdir
    else:
        # Fallback: scan for condition_* directories
        for d in sorted(glob.glob(os.path.join(experiment_dir, "condition_*"))):
            if os.path.isdir(d):
                label = os.path.basename(d).replace("condition_", "", 1)
                # Strip leading index_
                label = re.sub(r"^\d+_", "", label)
                conditions[label] = d

    return conditions


def parse_ping_rtt_avg(ping_path):
    """Parse avg RTT from a ping output file.
    Returns avg RTT in ms, or None if not found.
    """
    if not os.path.isfile(ping_path):
        return None

    with open(ping_path) as f:
        for line in f:
            if "rtt min/avg/max/mdev" in line:
                try:
                    rhs = line.split("=")[1].strip()
                    avg = float(rhs.split("/")[1])
                    return avg
                except (IndexError, ValueError):
                    return None
    return None


